local name_index = {}
for name, char in pairs(emoji_map) do
  table.insert(name_index, { name = name, char = char })
end

function M.search(query)
  if not query or #query == 0 then return {} end
  local q = query:lower():gsub("^:+", ""):gsub(":+$", "")
  local results = {}
  for _, entry in ipairs(name_index) do
    if entry.name:find(q, 1, true) then
      table.insert(results, entry)
    end
  end
  table.sort(results, function(a, b)
    local a_prefix = a.name:sub(1, #q) == q
    local b_prefix = b.name:sub(1, #q) == q
    if a_prefix ~= b_prefix then return a_prefix end
    return #a.name < #b.name
  end)
  local limited = {}
  for i = 1, math.min(#results, 50) do
    table.insert(limited, results[i])
  end
  return limited
end

function M.get(name)
  return emoji_map[name]
end

-- Build reverse map: char → first name
local reverse_map = {}
for name, char in pairs(emoji_map) do
  if not reverse_map[char] then
    reverse_map[char] = name
  elseif not reverse_map[char]:match("^e[0-9a-f]") and name:match("^e[0-9a-f]") then
    -- Keep existing text name
  elseif reverse_map[char]:match("^e[0-9a-f]") and not name:match("^e[0-9a-f]") then
    -- Replace hex name with text name
    reverse_map[char] = name
  end
end

function M.get_name(char)
  return reverse_map[char]
end

function M.get_all()
  return name_index
end

return M
